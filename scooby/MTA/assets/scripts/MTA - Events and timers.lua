addEvent('friends:hello', false)
addEventHandler('friends:hello', root, function(name)
    outputDebugString('Hello, ' .. name .. '!')
end)
addEventHandler('onClientResourceStart', resourceRoot, function()
    triggerEvent('friends:hello', root, getResourceName(getThisResource()))
end)

local heartbeat = setTimer(function()
    local state = mta.getSession()
    outputDebugString(state.ready and 'MTA session ready' or 'Waiting for MTA')
end, 5000, 0)

addEventHandler('onScoobySessionStart', root, function()
    outputDebugString('Local player available')
end)
addEventHandler('onScoobySessionEnd', root, function()
    outputDebugString('Local player no longer available')
end)
addEventHandler('onClientResourceStop', resourceRoot, function()
    killTimer(heartbeat)
    outputDebugString('Script stopped; callbacks and timers released')
end)
