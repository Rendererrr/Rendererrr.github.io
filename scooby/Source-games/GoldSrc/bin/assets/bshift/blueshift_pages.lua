  ui.feature("bs.friendly");ui.feature("bs.hostile");ui.feature("bs.players")
  ui.feature("bs.weapons");ui.feature("bs.items");ui.feature("bs.projectiles");ui.feature("bs.objectives")
 end)
end)
ui.tab("world","World",function()
 ui.columns(2,function()
  ui.group("Model appearance",function()
   ui.feature("bs.chams");ui.feature("bs.hidden");ui.feature("bs.viewmodel")
   local changed,value=ui.combo("Material",blueshift.setting("bs.chams","style")+1,{"Tinted","Flat","Wireframe","Additive"})
   if changed then blueshift.setting("bs.chams","style",value-1) end
  end)
  ui.next_column()
  ui.group("Animation",function()
   ui.feature("chams.animation")
   local changed,mode=ui.combo("Animation mode",blueshift.setting("chams.animation","style")+1,{"Pulse","Color fade","Rainbow"})
   if changed then blueshift.setting("chams.animation","style",mode-1) end
   local changed,speed=ui.slider("Speed (cycles/sec)",blueshift.setting("chams.animation_speed","distance"),0.05,3)
   if changed then blueshift.setting("chams.animation_speed","distance",speed) end
   local changed,strength=ui.slider("Strength",blueshift.setting("chams.animation_strength","distance"),0,1)
   if changed then blueshift.setting("chams.animation_strength","distance",strength) end
  end)
  ui.group("World / VFX",function()
   ui.feature("bs.grade")
  end)
 end)
end,{section='Visuals'})
