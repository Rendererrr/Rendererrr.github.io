ui.tab("world","World",function()
 ui.columns(2,function()
  ui.group("Model appearance",function()
   ui.feature("hl.chams");ui.feature("hl.hidden");ui.feature("hl.viewmodel")
   local changed,value=ui.combo("Material",halflife.setting("hl.chams","style")+1,{"Tinted","Flat","Wireframe","Additive"})
   if changed then halflife.setting("hl.chams","style",value-1) end
  end)
  ui.next_column()
  ui.group("Animation",function()
   ui.feature("chams.animation")
   local changed,mode=ui.combo("Animation mode",halflife.setting("chams.animation","style")+1,{"Pulse","Color fade","Rainbow"})
   if changed then halflife.setting("chams.animation","style",mode-1) end
   local changed,speed=ui.slider("Speed (cycles/sec)",halflife.setting("chams.animation_speed","distance"),0.05,3)
   if changed then halflife.setting("chams.animation_speed","distance",speed) end
   local changed,strength=ui.slider("Strength",halflife.setting("chams.animation_strength","distance"),0,1)
   if changed then halflife.setting("chams.animation_strength","distance",strength) end
  end)
  ui.group("World / VFX",function()
   ui.feature("hl.grade")
  end)
 end)
end,{section='Visuals'})
